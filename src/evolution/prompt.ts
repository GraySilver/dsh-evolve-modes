export interface EvolutionLearningMessage {
  readonly sessionId: string
  readonly turn: number
  readonly eventSeq: number
  readonly role: 'user' | 'assistant'
  readonly text: string
}

export interface EvolutionLearningInput {
  readonly sessionId: string
  readonly messages: readonly EvolutionLearningMessage[]
  readonly settings: readonly EvolutionSetting[]
  readonly proposals: readonly EvolutionProposal[]
}

const operationSchema = z.object({
  action: z.enum(['add', 'update', 'delete']),
  settingId: z.string().min(1).nullable(),
  scope: z.literal('global'),
  category: z.enum(['identity', 'preference', 'work_rule']).nullable(),
  content: z.string().min(1).max(2000).nullable(),
  inference: z.enum(['explicit', 'implicit']),
  deleteReason: z.enum(['explicit_denial', 'expired', 'replaced']).nullable(),
  evidence: z.array(z.object({
    eventSeq: z.number().int().nonnegative(),
    excerpt: z.string().min(1).max(500),
  }).strict()).min(1),
}).strict()

const learningResultSchema = z.object({ operations: z.array(operationSchema) }).strict()

function instructionRows(settings: readonly EvolutionSetting[]): string[] {
  const titles = {
    identity: 'Identity and background',
    preference: 'Preferences',
    work_rule: 'Work requirements',
  } as const
  const rows: string[] = []
  for (const category of ['identity', 'preference', 'work_rule'] as const) {
    const items = settings.filter(item => item.category === category)
    if (items.length === 0) continue
    rows.push(`## ${titles[category]}`)
    for (const item of items) rows.push(`- ${item.content}`)
  }
  return rows
}

/** Compile all approved instructions into one global request section. */
export function compileLearnedInstructions(state: EvolutionState): string {
  const global = state.settings.filter(item => item.scope === 'global')
  if (global.length === 0) return ''
  const rows = [
    EVOLUTION_PROMPT_OPEN,
    'The following instructions were explicitly approved for future work. Follow them when relevant unless a higher-priority instruction or the current user request conflicts.',
  ]
  rows.push('', '# Global learned instructions', '', ...instructionRows(global))
  rows.push(EVOLUTION_PROMPT_CLOSE)
  return rows.join('\n')
}

function learningInputPayload(input: EvolutionLearningInput): object {
  return {
    sessionId: input.sessionId,
    settings: input.settings.map(item => ({
      id: item.id,
      scope: item.scope,
      category: item.category,
      content: item.content,
      evidence: item.evidence,
    })),
    pendingProposals: input.proposals.filter(item => item.status === 'pending').map(item => ({
      id: item.id,
      action: item.action,
      scope: item.scope,
      category: item.category,
      content: item.content,
      targetId: item.targetId,
      inference: item.inference,
      deleteReason: item.deleteReason,
      evidence: item.evidence,
    })),
    messages: input.messages,
  }
}

/** Serialize one isolated learning batch as data for the single user message. */
export function evolutionLearningPrompt(input: EvolutionLearningInput): string {
  return JSON.stringify({
    mode: 'analyze',
    input: learningInputPayload(input),
  }, null, 2)
}

/** Serialize a failed result as data for one fresh isolated repair call. */
export function evolutionLearningRepairPrompt(
  input: EvolutionLearningInput,
  previousOutput: string,
  error: unknown,
): string {
  return JSON.stringify({
    mode: 'repair',
    input: learningInputPayload(input),
    validationError: error instanceof Error ? error.message : String(error),
    previousOutput,
  }, null, 2)
}

function jsonPayload(text: string): string {
  const trimmed = text.trim()
  const fenced = /^```(?:json)?\s*([\s\S]*?)\s*```$/u.exec(trimmed)
  if (fenced?.[1] !== undefined) return fenced[1]
  const start = trimmed.indexOf('{')
  const end = trimmed.lastIndexOf('}')
  return start === -1 || end < start ? trimmed : trimmed.slice(start, end + 1)
}

/** Parse and validate a model learning result against current settings and exact user-message evidence. */
export function parseEvolutionLearningResult(
  text: string,
  input: EvolutionLearningInput,
): EvolutionProposalDraft[] {
  const parsed: unknown = JSON.parse(jsonPayload(text))
  const result = learningResultSchema.parse(parsed)
  const messages = new Map(input.messages.filter(item => item.role === 'user').map(item => [item.eventSeq, item]))
  const settings = new Map(input.settings.map(item => [item.id, item]))
  const drafts: EvolutionProposalDraft[] = []
  for (const operation of result.operations) {
    if (operation.scope !== 'global') throw new Error('Project-scoped learning proposals are no longer supported.')
    if (operation.action === 'add') {
      if (operation.settingId !== null || operation.category === null || operation.content === null || operation.deleteReason !== null) {
        throw new Error('The learning result contains an invalid add operation.')
      }
    } else {
      if (operation.settingId === null) throw new Error(`${operation.action} requires an existing setting id.`)
      const target = settings.get(operation.settingId)
      if (target === undefined) throw new Error(`${operation.action} references an unknown setting.`)
      if (target.scope !== 'global' || target.projectRoot !== null) {
        throw new Error(`${operation.action} references a setting in a different scope.`)
      }
      if (operation.action === 'update'
        && (operation.category === null || operation.content === null || operation.deleteReason !== null)) {
        throw new Error('The learning result contains an invalid update operation.')
      }
      if (operation.action === 'delete'
        && (operation.category !== null || operation.content !== null || operation.deleteReason === null)) {
        throw new Error('The learning result contains an invalid delete operation.')
      }
    }
    const evidence = operation.evidence.map(item => {
      const message = messages.get(item.eventSeq)
      if (message === undefined || !message.text.includes(item.excerpt)) {
        throw new Error('Learning evidence must be copied exactly from a supplied user message.')
      }
      return {
        sessionId: message.sessionId,
        turn: message.turn,
        eventSeq: message.eventSeq,
        excerpt: item.excerpt,
      }
    })
    drafts.push({
      scope: operation.scope,
      projectRoot: null,
      action: operation.action,
      category: operation.category,
      content: operation.content?.trim() ?? null,
      targetId: operation.settingId,
      inference: operation.inference,
      deleteReason: operation.deleteReason,
      evidence,
    })
  }
  return drafts
}
